import type { ProjectInfo } from "./detect.js";

export interface GeneratedFile {
  /** Path relative to the project root, with forward slashes. */
  path: string;
  contents: string;
  /** How a developer (or their agent) uses the file once it exists. */
  usage: string;
}

const prefix = (srcDir: string) => (srcDir ? `${srcDir}/` : "");

// Exa's recommended defaults for agentic search: auto search type, highlights as the content.
const SEARCH_CALL = `exa.search(query, {
    type: "auto",
    numResults: 5,
    contents: { highlights: true },
  })`;

function nextAppRoute(ts: boolean): string {
  return `import Exa from "exa-js";

const exa = new Exa(process.env.EXA_API_KEY);

// GET /api/exa-search?q=your+question
export async function GET(request${ts ? ": Request" : ""}) {
  const query = new URL(request.url).searchParams.get("q");
  if (!query) {
    return Response.json({ error: "Add a query: /api/exa-search?q=your+question" }, { status: 400 });
  }

  const { results } = await ${SEARCH_CALL};

  return Response.json(
    results.map((r) => ({ title: r.title, url: r.url, highlights: r.highlights })),
  );
}
`;
}

function nextPagesRoute(ts: boolean): string {
  const types = ts ? `import type { NextApiRequest, NextApiResponse } from "next";\n` : "";
  const sig = ts ? "req: NextApiRequest, res: NextApiResponse" : "req, res";
  return `${types}import Exa from "exa-js";

const exa = new Exa(process.env.EXA_API_KEY);

// GET /api/exa-search?q=your+question
export default async function handler(${sig}) {
  const query = typeof req.query.q === "string" ? req.query.q : "";
  if (!query) {
    return res.status(400).json({ error: "Add a query: /api/exa-search?q=your+question" });
  }

  const { results } = await ${SEARCH_CALL};

  res.status(200).json(results.map((r) => ({ title: r.title, url: r.url, highlights: r.highlights })));
}
`;
}

function expressRouter(ts: boolean, esm: boolean): string {
  const imports = ts || esm
    ? `import { Router } from "express";\nimport Exa from "exa-js";`
    : `const { Router } = require("express");\nconst Exa = require("exa-js").default;`;
  const exportLine = ts || esm ? "export const exaRouter = Router();" : "const exaRouter = Router();";
  const tail = ts || esm ? "" : "\nmodule.exports = { exaRouter };\n";
  return `${imports}

const exa = new Exa(process.env.EXA_API_KEY);

// Mount it: app.use("/api", exaRouter) → GET /api/exa-search?q=your+question
${exportLine}

exaRouter.get("/exa-search", async (req, res, next) => {
  try {
    const query = typeof req.query.q === "string" ? req.query.q : "";
    if (!query) return res.status(400).json({ error: "Add a query: /api/exa-search?q=your+question" });

    const { results } = await ${SEARCH_CALL};

    res.json(results.map((r) => ({ title: r.title, url: r.url, highlights: r.highlights })));
  } catch (error) {
    next(error);
  }
});
${tail}`;
}

function nodeScript(): string {
  return `import Exa from "exa-js";

// Usage: node exa-search.mjs "your question"
const query = process.argv.slice(2).join(" ") || "latest research on retrieval-augmented generation";
const exa = new Exa(process.env.EXA_API_KEY);

const { results } = await ${SEARCH_CALL};

for (const r of results) {
  console.log(\`\\n\${r.title}\\n\${r.url}\`);
  for (const h of r.highlights ?? []) console.log(\`  · \${h}\`);
}
`;
}

/** The file that wires Exa into this kind of project. */
export function integrationFile(project: ProjectInfo): GeneratedFile {
  const p = prefix(project.srcDir);
  const ext = project.typescript ? "ts" : "js";
  switch (project.framework) {
    case "next-app":
      return {
        path: `${p}app/api/exa-search/route.${ext}`,
        contents: nextAppRoute(project.typescript),
        usage: "Start your dev server and open /api/exa-search?q=hello",
      };
    case "next-pages":
      return {
        path: `${p}pages/api/exa-search.${ext}`,
        contents: nextPagesRoute(project.typescript),
        usage: "Start your dev server and open /api/exa-search?q=hello",
      };
    case "express":
      return {
        path: `${p}exaSearch.${ext}`,
        contents: expressRouter(project.typescript, project.esm),
        usage: 'Mount it with app.use("/api", exaRouter), then open /api/exa-search?q=hello',
      };
    case "node":
      return {
        path: "exa-search.mjs",
        contents: nodeScript(),
        usage: 'node exa-search.mjs "your question"',
      };
  }
}

/**
 * A dependency-free script that makes one real call through the project's own
 * installed exa-js. Running it is the proof that the integration works here.
 */
export function checkScript(): GeneratedFile {
  return {
    path: "scripts/exa-check.mjs",
    contents: `// Generated by exa-quickstart: proves this project can reach Exa.
// Usage: EXA_API_KEY=... node scripts/exa-check.mjs   (or: node --env-file=.env.local scripts/exa-check.mjs)
import Exa from "exa-js";

if (!process.env.EXA_API_KEY) {
  console.error("EXA_API_KEY is not set. Get a key at https://dashboard.exa.ai/api-keys");
  process.exit(2);
}

const exa = new Exa(process.env.EXA_API_KEY);
const { results } = await exa.search("Exa search API documentation", { type: "auto", numResults: 1 });
console.log(JSON.stringify({ ok: true, title: results[0]?.title ?? null, url: results[0]?.url ?? null }));
`,
    usage: "node --env-file=.env.local scripts/exa-check.mjs",
  };
}
